/**
 * Blur placeholders for the photographs in public/landing and public/categories.
 *
 *   npm run landing:blur
 *
 * Writes src/components/landing/blur.generated.ts: for every JPEG, a 12px-wide
 * WebP as a data URL (about 150 bytes each), keyed by its public path. next/image
 * draws it blurred while the full picture loads (placeholder="blur"). Rerun after
 * adding or replacing a photograph; a missing entry only means no placeholder.
 *
 * sharp ships with next, so nothing extra is installed.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const DIRS = ['landing', 'categories'];
const OUT = path.join(ROOT, 'src/components/landing/blur.generated.ts');

function* walk(dir: string): Generator<string> {
  for (const name of readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (/\.(jpe?g|png|webp)$/i.test(name)) yield full;
  }
}

async function main() {
  const entries: [string, string][] = [];
  for (const dir of DIRS) {
    for (const file of walk(path.join(PUBLIC, dir))) {
      const buf = await sharp(file).rotate().resize(12).webp({ quality: 40 }).toBuffer();
      const key = '/' + path.relative(PUBLIC, file).split(path.sep).join('/');
      entries.push([key, `data:image/webp;base64,${buf.toString('base64')}`]);
    }
  }

  const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  writeFileSync(
    OUT,
    `// Generated by scripts/landing-blur.ts (npm run landing:blur). Do not edit.\n` +
      `// Tiny WebP previews of the landing and category photographs, for placeholder="blur".\n\n` +
      `export const BLUR: Readonly<Record<string, string>> = {\n${body}\n};\n`
  );
  console.log(`Wrote ${entries.length} placeholders to ${path.relative(ROOT, OUT)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
